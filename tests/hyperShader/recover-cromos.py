"""Recover only the water-related data from the operator-supplied ZIP.
No target execution and no bulk asset extraction. Evidence retains byte hashes.
"""
from pathlib import Path
import zipfile,json,hashlib
root=Path(__file__).resolve().parents[2]
source=root.parent/'Cromos_Realistic_V0_1_19_All_In_One.mcpack'
out=root/'evidence/cromos/recovered';out.mkdir(parents=True,exist_ok=True)
data=source.read_bytes();z=zipfile.ZipFile(source)
members={};profiles={};biomes={}
for name in z.namelist():
 if not name.startswith(('water/','fogs/','local_lighting/')) or not name.endswith('.json'):continue
 raw=z.read(name);parsed=json.loads(raw.decode('utf-8-sig'));(out/name.replace('/','__')).write_bytes(raw)
 members[name]={'size':len(raw),'sha256':hashlib.sha256(raw).hexdigest()}
 if name.startswith('water/'):
  p=parsed['minecraft:water_settings'];key=Path(name).stem
  profiles[key]={'particles':p['particle_concentrations'],'waves':p['waves'],'caustics':p['caustics'],'biomeContribution':p['biome_water_color_contribution']}
  fog=json.loads(z.read(f'fogs/underwater_{key}.json'))['minecraft:fog_settings']
  profiles[key]['fog']=fog['distance']['water'];profiles[key]['medium']=fog['volumetric']['media_coefficients']['water']
for name in z.namelist():
 if not name.startswith('biomes/') or not name.endswith('.json'):continue
 b=json.loads(z.read(name))['minecraft:client_biome']
 water=b['components'].get('minecraft:water_identifier',{}).get('water_identifier','')
 if water.startswith('cromos:water_'):biomes[b['description']['identifier'].removeprefix('minecraft:')]=water.removeprefix('cromos:water_')
evidence={'archive':str(source),'sha256':hashlib.sha256(data).hexdigest(),'entryCount':len(z.infolist()),'shaderMembers':[n for n in z.namelist() if n.endswith(('.glsl','.hlsl','.fsh','.vsh','.material.bin'))],'members':members,'profiles':profiles,'limitations':['Bedrock engine shader/SSR implementation is not included.','Particle concentrations cannot uniquely determine OpusCraft RGB extinction without Bedrock spectral coefficients.','This is recovered pack data plus an independent WebGL adaptation; not verified Bedrock parity.']}
(out.parent/'recovery.json').write_text(json.dumps(evidence,indent=2))
code='// Generated by tests/hyperShader/recover-cromos.py from Cromos V0.1.19.\n// See licenses/CROMOS-PROVENANCE.md for source identity and adaptation limits.\nexport const CROMOS_WATER = '+json.dumps(profiles,indent=2)+' as const;\nexport const CROMOS_BIOME_WATER = '+json.dumps(biomes,indent=2)+' as const;\n'
(root/'src/render/cromosWaterData.ts').write_text(code)
print(json.dumps({'entryCount':len(z.infolist()),'profiles':list(profiles),'shaderMembers':evidence['shaderMembers'],'sha256':evidence['sha256']},indent=2))
